//! Running SQL files and filling tables with dummy data.
use std::sync::atomic::AtomicBool;

use rowhouse_core::{fakegen::Gen, script::RunOptions, Connection, ConnectionConfig, DbKind};

async fn count(c: &Connection, sql: &str) -> i64 {
    let r = c.query(sql, 10).await.unwrap();
    let v = &r.results[0].rows[0][0];
    v.as_i64()
        .or_else(|| v.as_str().and_then(|s| s.parse().ok()))
        .unwrap()
}

async fn exercise(c: &Connection, dir: &std::path::Path, parent: &str, child: &str, ddl: &str) {
    let f = dir.join("seed.sql");
    std::fs::write(&f, ddl).unwrap();
    let mut seen = 0;
    let p = c
        .run_sql_file(
            &f,
            &RunOptions {
                continue_on_error: true,
            },
            &AtomicBool::new(false),
            |p| seen = p.done,
        )
        .await
        .unwrap();
    assert!(p.finished && seen == p.total, "{p:?}");
    assert_eq!(
        p.failed, 1,
        "exactly the bad statement fails: {:?}",
        p.errors
    );
    assert!(p.errors[0].message.to_lowercase().contains("nope") || !p.errors[0].message.is_empty());
    assert_eq!(count(c, &format!("SELECT COUNT(*) FROM {parent}")).await, 3);

    // stop at the first error
    let p = c
        .run_sql_file(&f, &RunOptions::default(), &AtomicBool::new(false), |_| {})
        .await
        .unwrap();
    assert_eq!(p.failed, 1);
    assert!(p.done < p.total || p.errors[0].index == p.total - 1);

    // dummy data: FK column picks existing parents, ids are skipped/sequenced
    let (schema, table) = child.split_once('.').unwrap_or(("main", child));
    let plan = c.fake_plan(schema, table).await.unwrap();
    let fk = plan.iter().find(|g| g.column == "parent_id").unwrap();
    assert!(
        matches!(&fk.gen, Gen::Reference { .. } | Gen::Nullable { .. }),
        "{:?}",
        fk.gen
    );
    let prev = c.fake_preview(&plan, 5, 42).await.unwrap();
    assert_eq!(prev.rows.len(), 5);
    let mut last = 0;
    let n = c
        .fake_insert(schema, table, &plan, 1203, 42, |d| last = d)
        .await
        .unwrap();
    assert_eq!((n, last), (1203, 1203));
    assert_eq!(
        count(c, &format!("SELECT COUNT(*) FROM {child}")).await,
        1203
    );
    assert_eq!(
        count(c, &format!("SELECT COUNT(*) FROM {child} WHERE parent_id IS NOT NULL AND parent_id NOT IN (SELECT id FROM {parent})")).await,
        0
    );
}

#[tokio::test]
async fn sqlite_script_and_fake() {
    let dir = tempfile::tempdir().unwrap();
    let f = dir.path().join("a.db");
    std::fs::File::create(&f).unwrap();
    let mut cfg = ConnectionConfig::new("s", DbKind::Sqlite);
    cfg.file = Some(f.to_string_lossy().into());
    let c = Connection::connect(&cfg).await.unwrap();
    let ddl = "-- seed\nCREATE TABLE parent (id INTEGER PRIMARY KEY, name TEXT NOT NULL);\n\
               INSERT INTO parent (name) VALUES ('a'), ('b;c'), ('d');\n\
               SELECT nope FROM nowhere;\n\
               CREATE TABLE child (id INTEGER PRIMARY KEY AUTOINCREMENT, parent_id INTEGER REFERENCES parent(id), email TEXT, qty INTEGER, created_at TEXT, active BOOLEAN);\n";
    exercise(&c, dir.path(), "parent", "child", ddl).await;
}

#[tokio::test]
async fn postgres_script_and_fake() {
    let Ok(spec) = std::env::var("ROWHOUSE_TEST_PG") else {
        return;
    };
    let mut p = spec.split(':');
    let mut cfg = ConnectionConfig::new("pg", DbKind::Postgres);
    cfg.host = p.next().map(Into::into);
    cfg.port = p.next().and_then(|x| x.parse().ok());
    cfg.user = p.next().map(Into::into);
    cfg.database = Some("postgres".into());
    let pw = std::env::var("ROWHOUSE_TEST_PG_PASSWORD").ok();
    let c = Connection::connect_with(&cfg, pw.as_deref()).await.unwrap();
    c.query("DROP SCHEMA IF EXISTS rh_fake CASCADE", 10)
        .await
        .unwrap();
    let dir = tempfile::tempdir().unwrap();
    let ddl = "CREATE SCHEMA rh_fake;\n\
               CREATE TABLE rh_fake.parent (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);\n\
               CREATE FUNCTION rh_fake.f() RETURNS int LANGUAGE plpgsql AS $$ BEGIN RETURN 1; END $$;\n\
               INSERT INTO rh_fake.parent (name) VALUES ('a'), ('b;c'), ('d');\n\
               SELECT nope FROM nowhere;\n\
               CREATE TABLE rh_fake.child (id serial PRIMARY KEY, parent_id bigint REFERENCES rh_fake.parent(id), email text, qty int, total numeric(10,2), created_at timestamptz DEFAULT now(), active boolean, meta jsonb, ref uuid);\n";
    exercise(&c, dir.path(), "rh_fake.parent", "rh_fake.child", ddl).await;
    c.query("DROP SCHEMA rh_fake CASCADE", 10).await.unwrap();
}

#[tokio::test]
async fn mysql_script_and_fake() {
    let Ok(spec) = std::env::var("ROWHOUSE_TEST_MYSQL") else {
        return;
    };
    let p: Vec<&str> = spec.split(':').collect();
    let mut cfg = ConnectionConfig::new("my", DbKind::Mysql);
    cfg.host = Some(p[0].into());
    cfg.port = p[1].parse().ok();
    cfg.user = Some(p[2].into());
    cfg.database = Some(p[4].into());
    let c = Connection::connect_with(&cfg, Some(p[3])).await.unwrap();
    c.query("DROP TABLE IF EXISTS rh_child; DROP TABLE IF EXISTS rh_parent; DROP TRIGGER IF EXISTS rh_parent_trg;", 10).await.unwrap();
    let dir = tempfile::tempdir().unwrap();
    let db = p[4];
    let ddl = "CREATE TABLE rh_parent (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(40) NOT NULL);\n\
               DELIMITER ;;\nCREATE TRIGGER rh_parent_trg BEFORE INSERT ON rh_parent FOR EACH ROW BEGIN SET NEW.name = TRIM(NEW.name); END;;\nDELIMITER ;\n\
               INSERT INTO rh_parent (name) VALUES ('a'), ('b;c'), ('d');\n\
               SELECT nope FROM nowhere;\n\
               CREATE TABLE rh_child (id INT AUTO_INCREMENT PRIMARY KEY, parent_id INT, email VARCHAR(120), qty INT, total DECIMAL(10,2), created_at DATETIME, active TINYINT(1), FOREIGN KEY (parent_id) REFERENCES rh_parent(id));\n";
    exercise(
        &c,
        dir.path(),
        &format!("{db}.rh_parent"),
        &format!("{db}.rh_child"),
        ddl,
    )
    .await;
    c.query("DROP TABLE rh_child; DROP TABLE rh_parent;", 10)
        .await
        .unwrap();
}
